#!/usr/bin/env python3
"""З15-и6а «Табель в сутки перевода часов» (из «Найдено по дороге» З15-и6, решение основателя 27.10). Табель собирал
время как «полночь клуба + N минут», а в сутках перевода часов (последнее воскресенье октября и марта) 25 или 23 часа —
время после перевода уходило на час: 25.10.2026 забытая «День 08–20» закрылась по графику в 19:00 (660 минут вместо
720), правка владельца «09:00–21:00» легла как 08:00–20:00, в марте — на час позже. Теперь время собирается стенными
часами клуба. Проверка — на 25.10.2026 и 29.03.2026 и от сегодняшней даты не зависит: забытая «День» закрывается по
графику при «Я пришёл», правка владельца, ручные записи днём и ночью — в том числе ночь через перевод (осенью 13 часов,
весной 11). Вход z15s — без признака админки: смену такой вход не открывает. Временный z15s — сотрудник: его записи
табеля удаляются в начале и в конце; денег не трогает."""
from _z import *

Z = "z15s"
zid = hire_temp(Z)
drop = lambda: sql(f"DELETE FROM work_entries WHERE user_id = '{zid}'")
drop()
at_end(drop)
club = sql("SELECT id FROM clubs ORDER BY created_at LIMIT 1")
day_id = sql("SELECT id FROM shifts WHERE name = 'День' AND start_min = 480 AND end_min = 1200 ORDER BY created_at LIMIT 1")
local = lambda col: f"to_char({col} AT TIME ZONE '{TZ}', 'DD.MM HH24:MI')"
row = lambda e: sql(f"SELECT {local('started_at')} || '—' || {local('ended_at')} || '|' || minutes || '|' || auto_closed "
                    f"FROM work_entries WHERE id = '{e}'") if e else ""


def add(date, start, end, note):
    """Ручная запись табеля z15s от владельца: (код, id)."""
    s, d = api("POST", "/admin/work", {"nickname": Z, "date": date, "start": start, "end": end, "note": note}, "boss")
    return s, ((d or {}).get("entry") or {}).get("id", "")


section("25.10.2026 — сутки на час длиннее")
e1 = sql(f"INSERT INTO work_entries (club_id, user_id, shift_id, shift_name, date, started_at, note, created_by) VALUES "
         f"('{club}', '{zid}', '{day_id}', 'День', '2026-10-25', {at_club('2026-10-25', '08:00')}, 'z15s забытая', '{zid}') "
         f"RETURNING id")
s, d = login(Z)  # без client — вход не админки, смену не открывает
s1, d1 = api("POST", "/admin/work/start", {}, token=(d or {}).get("access_token", ""))  # прошлая не закрыта — закроется по графику
sql(f"DELETE FROM work_entries WHERE user_id = '{zid}' AND ended_at IS NULL")  # сегодняшняя запись проверке не нужна
check("забытая «День 08–20» с 25.10 закрыта по графику при «Я пришёл»: 08:00—20:00, 720 минут, автозакрытие",
      day_id != "" and s1 == 201 and (d1 or {}).get("auto_closed_previous") is True and row(e1) == "25.10 08:00—25.10 20:00|720|true",
      f"{s1} {row(e1)}")
s2, _ = api("PATCH", f"/admin/work/{e1}", {"start": "09:00", "end": "21:00", "note": "z15s правка"}, "boss")
check("правка владельца «09:00–21:00» 25.10 легла как есть: 09:00—21:00, 720 минут", s2 == 200
      and row(e1) == "25.10 09:00—25.10 21:00|720|false", f"{s2} {row(e1)}")
s3, e3 = add("2026-10-25", "21:30", "08:00", "z15s ночь с 25.10")
s4, e4 = add("2026-10-24", "20:00", "08:00", "z15s ночь через перевод")
check("ночь с 25.10 «21:30–08:00» — 21:30—08:00, 630 минут; ночь 24.10 → 25.10 «20:00–08:00» через перевод — до 08:00, "
      "780 минут (часы перевели назад)", (s3, s4) == (201, 201) and row(e3) == "25.10 21:30—26.10 08:00|630|false"
      and row(e4) == "24.10 20:00—25.10 08:00|780|false", f"{s3} {s4} {row(e3)} · {row(e4)}")

section("29.03.2026 — сутки на час короче")
s5, e5 = add("2026-03-29", "09:00", "21:00", "z15s день 29.03")
s6, e6 = add("2026-03-28", "20:00", "08:00", "z15s ночь через перевод")
check("29.03 «09:00–21:00» — 09:00—21:00, 720 минут; ночь 28.03 → 29.03 «20:00–08:00» через перевод — до 08:00, 660 минут",
      (s5, s6) == (201, 201) and row(e5) == "29.03 09:00—29.03 21:00|720|false"
      and row(e6) == "28.03 20:00—29.03 08:00|660|false", f"{s5} {s6} {row(e5)} · {row(e6)}")
done()
