// З6-и3 (OWNER.md, трек З; №40): деньги и числа из форм — только валидные.
//
// Цены в базе — DECIMAL(8,2) с CHECK (> 0), а сервер пропускал любое
// положительное число: цена 0,004 zł округлялась базой до 0,00 и падала на
// CHECK ошибкой сервера, 1,005 zł принималась — в ответе 1,005, в базе 1,01.
// Порядок в списках и количество в приходе склада — int4 в базе и без
// верхней границы на сервере: 3·10⁹ тоже падало ошибкой сервера. Теперь на
// кривой ввод — отказ 400 с кодом поля и понятной фразой.

import (
	"fmt"
	"math"
)

const (
	maxSort      = 10000   // порядок в списках (зоны, товары, пакеты, каталог, шаблоны смен): ±10 000
	maxStockQty  = 1000000 // штук: остаток позиции, один приход, одна корректировка
	maxStockNote = 200     // символов в примечании к приходу и корректировке (З-Р36)
)

var sortMessage = fmt.Sprintf("Порядок — от -%d до %d", maxSort, maxSort)

// validatePLN — сумма в злотых из формы владельца: от 0,01 до max и не больше
// двух знаков после запятой. Чистая функция (тест). NaN не проходит: любое
// сравнение с ним ложно.
func validatePLN(v, max float64) bool {
	if !(v >= 0.01 && v <= max) {
		return false
	}
	cents := v * 100
	// 19,99·100 = 1998,9999999999998 — это два знака; 1,005·100 = 100,49999… — три.
	return math.Abs(cents-math.Round(cents)) < 1e-6
}

// validSort — порядок в списке: не прислан или в пределах ±maxSort.
func validSort(sort *int) bool {
	return sort == nil || (*sort >= -maxSort && *sort <= maxSort)
}
