-- 064 — Ж4-и1 (ADMIN.md, трек Ж, решение Ж-Р6): посадка на ПК без связи.
--
-- До этой миграции посадка от стойки на выключенную машину открывала обычное
-- окно [Готов!]: гость нажать не мог (экран тёмный), и через ready_wait_min
-- (7 мин) сессия стартовала САМА и списывала деньги за пустой ПК — пока админ
-- не замечал (ревью 14.09, №9–10). Теперь у сессии есть третье состояние —
-- «ждёт шелл»: shell_wait_until IS NOT NULL AND ready_at IS NULL. Пока оно
-- длится, деньги не текут; агент подключился — с этого момента начинается
-- обычное окно [Готов!] (ready_deadline проставляется, shell_wait_until
-- снимается); не подключился до shell_wait_until — посадка снимается без
-- списания (cancelled, ended_reason = shell_offline), админу — сигнал.
--
-- Статус сессии по-прежнему не трогаем (образец пауз Г2 и окна Е1, миграции
-- 033/045): ожидание держится полями, а не enum.

ALTER TABLE sessions ADD COLUMN IF NOT EXISTS shell_wait_until TIMESTAMPTZ;

COMMENT ON COLUMN sessions.shell_wait_until IS 'Ж4 (Ж-Р6): посадка ждёт подключения шелла до этого момента; NULL — не ждёт (шелл был на связи или уже пришёл)';
