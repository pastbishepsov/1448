-- 097 — З22-и1 (OWNER.md, трек З; №59, З-Р28): журнал отправленных алертов — защита от повторов.
--
-- Алерт — служебное сообщение канала персонала (З1-и2): сервер сам пишет, когда что-то требует внимания. Каждый вид
-- шлёт свой ключ — «раз за событие» (id сдачи кассы, отмены, позиции склада) или «раз за день» (клубные сутки и
-- предмет). Строка здесь — ключ уже уходил: второй прогон проверки и гонка двух запросов упираются в первичный ключ и
-- молчат. Само сообщение — в staff_messages; удалили его — запись о том, что ключ уходил, остаётся.
--
-- Идемпотентна: IF NOT EXISTS.

CREATE TABLE IF NOT EXISTS alerts_sent (
    kind    VARCHAR(32)  NOT NULL,
    key     VARCHAR(128) NOT NULL,
    sent_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (kind, key)
);

COMMENT ON TABLE alerts_sent IS 'З22-и1: какие алерты уже ушли в канал персонала — вид и ключ (событие или клубные сутки и предмет)';
