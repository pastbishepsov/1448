-- 086 — З15-и4 (OWNER.md, трек З; №30; З-Р20): имя смены — снимком в записи табеля.
--
-- Запись табеля знала смену только ссылкой shift_id, а удаление шаблона её обнуляет (ON DELETE SET NULL, 026): табель
-- терял имя смены, «Персонал → по сменам» относил деньги и сессии этой смены «вне смен» или в соседнюю, а переименование
-- шаблона переписывало историю. Теперь имя пишется в запись, когда она открывается (вход в админку, «Я пришёл»,
-- ручная запись владельца), и дальше не меняется: шаблон удалили, переименовали или выключили — в табеле и отчёте
-- имя то, с которым человек работал. Пустая строка — запись вне смены.
--
-- Старые записи получают имя своего шаблона, если он ещё есть. У записей, чей шаблон удалён до этой миграции, shift_id
-- уже обнулён — их имя не восстановить, они остаются без имени.
--
-- Идемпотентна: колонка — IF NOT EXISTS, заполняются только пустые имена.

ALTER TABLE work_entries ADD COLUMN IF NOT EXISTS shift_name VARCHAR(32) NOT NULL DEFAULT '';

UPDATE work_entries w
   SET shift_name = s.name
  FROM shifts s
 WHERE w.shift_id = s.id
   AND w.shift_name = '';
