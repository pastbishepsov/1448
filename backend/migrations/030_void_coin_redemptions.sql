-- 030: отмена выдачи времени за монеты (спринт В4, этап 4; ADMIN.md).
-- Потолок минут за одну выдачу убран по решению основателя: гостя ограничивает
-- его собственный баланс, а лимит на операцию админ обходит повтором — значит
-- он защищал только от лишнего клика, а не от растраты.
--
-- Настоящая дыра была в другом: ошибочную выдачу нельзя было откатить. У
-- продаж товара отмена есть с самого начала, у погашения монет не было —
-- промахнулся, и монеты списаны, а время отдано. Здесь это выравнивается:
-- отмена возвращает монеты на баланс, строка остаётся в истории с пометкой.

ALTER TABLE coin_redemptions ADD COLUMN IF NOT EXISTS voided_at TIMESTAMPTZ;
ALTER TABLE coin_redemptions ADD COLUMN IF NOT EXISTS voided_by UUID REFERENCES users(id);

COMMENT ON COLUMN coin_redemptions.voided_at IS 'Отменённая выдача: монеты вернулись, строка осталась';
