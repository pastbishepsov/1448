-- 056_no_pause_default.sql
-- К4-и4 (KIOSK.md, решение основателя 07.09): паузы нет — клуб зарабатывает,
-- пока гость держит ПК. Бесплатная «передышка» (pause_limit_min, деф. был 15
-- мин на сессию) выключается: 0. Порог простоя AFK — 25 минут: за 5 минут до
-- него гость получает предупреждение (тост поверх игры), на пороге сессия
-- завершается, ПК свободен, агент закрывает игру и чистит профиль, киоск
-- разлогинивает.
--
-- Владелец другого клуба может включить паузу обратно в админке — механика и
-- настройка остаются. Здесь ON CONFLICT DO UPDATE сознательно: миграция
-- выполняется один раз (журнал schema_migrations) и переводит уже
-- настроенные клубы на новое правило.

INSERT INTO settings (key, value) VALUES
    ('pause_limit_min', '0'),   -- пауза выключена
    ('afk_stop_min', '25')      -- 25 минут тишины → завершение
ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value;
