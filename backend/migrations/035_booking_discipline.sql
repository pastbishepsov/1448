-- 035: дисциплина броней (трек Г, спринт Г4; GUEST.md, этап II).
--
-- Гейт: бронь — привилегия уровня (booking_min_level, деф. 3, 0 = выкл):
-- мотивация качаться, а не стена — клиенты показывают «откроется на LVL N».
-- Админского walk-in у стойки гейт не касается (операционка).
-- Лимит живых броней на гостя (max_active_bookings, деф. 2, 0 = без лимита) —
-- нельзя обвешать бронями весь зал.
-- No-show: бронь не выкуплена за no_show_min (деф. 15, 0 = выкл) от начала →
-- статус no_show (enum уже был с миграции 007), гостю уведомление, счётчик
-- в карточке гостя (санкции — отдельное решение владельца, пока копим факт),
-- освободившееся окно зовёт вейтлист (Б9). Если гость в клубе за другим ПК —
-- бронь честно гасится seated, а не no_show: человек пришёл.
-- Напоминания «бронь через ~60/~15 минут» — шина Б4, по одному разу
-- (штампы remind60_at/remind15_at ниже).

ALTER TABLE bookings ADD COLUMN IF NOT EXISTS remind60_at TIMESTAMPTZ;
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS remind15_at TIMESTAMPTZ;

INSERT INTO settings (key, value) VALUES
    ('booking_min_level', '3'),   -- бронь с этого уровня; 0 = всем
    ('max_active_bookings', '2'), -- живых броней на гостя; 0 = без лимита
    ('no_show_min', '15')         -- минут от начала брони до сгорания; 0 = выкл
ON CONFLICT (key) DO NOTHING;

COMMENT ON COLUMN bookings.remind60_at IS 'Г4: напоминание «через ~60 мин» отправлено';
