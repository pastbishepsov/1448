-- 087 — З15-и4а (OWNER.md, трек З; решение основателя 22.10): имя смены у старых записей табеля — из журнала прихода.
--
-- 086 дала записям табеля имя смены снимком, но записи, чей шаблон удалили раньше, остались без имени: ссылку shift_id
-- удаление шаблона уже обнулило. Имя при этом есть в журнале: запись, которую человек открыл сам — входом или «Я
-- пришёл» (created_by = он сам), — сервер всегда сопровождал строкой work_start от него же в ту же секунду: «пришёл ·
-- День», «вход в систему · День» (до 24.09) или «вход в админку · День». Отсюда имя и берём: запись без имени и без
-- шаблона, открытая самим человеком, и его строка work_start в пределах двух секунд от создания записи (не от начала:
-- начало владелец мог поправить), из нескольких — ближайшая.
--
-- Не трогаем: записи с именем; записи «вне смены» (в журнале «… (вне смены)» — имени нет); ручные записи владельца —
-- их открыл не сам человек, в журнале у них правка табеля без смены; они остаются без имени.
--
-- Идемпотентна: заполняются только пустые имена, повторный прогон ничего не меняет.

WITH found AS (
    SELECT DISTINCT ON (w.id)
           w.id,
           left((regexp_match(a.details, '^(?:пришёл|вход в систему|вход в админку) · (.+)$'))[1], 32) AS name
      FROM work_entries w
      JOIN admin_actions a
        ON a.admin_id = w.user_id
       AND a.action = 'work_start'
       AND a.created_at BETWEEN w.created_at - interval '2 seconds' AND w.created_at + interval '2 seconds'
       AND a.details ~ '^(пришёл|вход в систему|вход в админку) · .+$'
     WHERE w.shift_name = ''
       AND w.shift_id IS NULL
       AND w.created_by = w.user_id
     ORDER BY w.id, abs(extract(epoch FROM a.created_at - w.created_at))
)
UPDATE work_entries w
   SET shift_name = found.name
  FROM found
 WHERE w.id = found.id
   AND found.name <> '';
