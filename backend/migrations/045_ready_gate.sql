-- 045: окно [Готов!] перед стартом сессии (спринт Е1, OPERATOR.md).
--
-- Лист основателя, приписка внизу: «Активирует окошко на компьютере, чтобы
-- гость нажал [Готов!], когда сядет за комп, чтобы не списывать коинсы за то,
-- что он идёт к компу. (не больше 7 минут!)».
--
-- До этого спринта деньги начинали течь в момент посадки у стойки: гость ещё
-- шёл через зал, а кошелёк уже худел. На семи минутах при 12 zł/час это
-- полтора злотых с каждой посадки — мелочь для клуба и очень заметная
-- несправедливость для гостя, который это видит на своём экране.
--
-- Состояние ожидания = ready_deadline IS NOT NULL AND ready_at IS NULL.
-- Статус сессии НЕ трогаем (остаётся active) — ровно по образцу паузы
-- (Г2-и1, миграция 033): иначе пришлось бы переписывать все выборки по enum,
-- а их в проекте десятки.
--
-- Р1 основателя: не нажал за ready_wait_min — списание стартует САМО, посадку
-- не снимаем. Гость мог отойти, засмотреться, разговориться у стойки; клуб
-- при этом держит за ним машину, и с какого-то момента она должна оплачиваться.
-- Снимать посадку — решение админа (отмена посадки), не автомата.

ALTER TABLE sessions ADD COLUMN IF NOT EXISTS ready_at       TIMESTAMPTZ;
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS ready_deadline TIMESTAMPTZ;

COMMENT ON COLUMN sessions.ready_at       IS 'Е1: когда гость нажал [Готов!] (или момент авто-старта по дедлайну); NULL при живом ожидании';
COMMENT ON COLUMN sessions.ready_deadline IS 'Е1: до какого момента ждём нажатия; NULL — окно выключено настройкой';

INSERT INTO settings (key, value) VALUES
    ('ready_wait_min', '7')  -- сколько ждём нажатия [Готов!], мин; 0 = окно выключено
ON CONFLICT (key) DO NOTHING;
