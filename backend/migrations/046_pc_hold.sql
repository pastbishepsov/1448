-- 046: придержать ПК под регистрацию нового гостя (спринт Е1-и5, OPERATOR.md).
--
-- Лист основателя: «новый — сажает за свободный комп для регистрации».
-- Посадить его нельзя — аккаунта ещё нет, а значит и ника, по которому
-- сажают. Сегодня админ просто включает машину и говорит «иди туда»; всё это
-- время ПК числится свободным, и его законно занимает следующий гость или
-- второй админ. Человек доходит до места и обнаруживает там чужого.
--
-- Придержание — не статус, а метка со сроком: hold_until (докуда держим) и
-- hold_by (кто придержал, для журнала и разбора «почему занято»). Отдельный
-- статус заводить не стали — машина физически свободна, просто её не надо
-- предлагать автоматике; сравнение `hold_until > now()` само отпускает ПК,
-- если про него забыли, и фоновый джоб для этого не нужен.
--
-- Правило простое: придержание убирает ПК из АВТОМАТИЧЕСКОГО выбора («первый
-- свободный»), но явный старт именно на этой машине проходит и снимает метку.
-- Иначе получилось бы, что мы держим ПК для гостя и ему же не даём сесть.

ALTER TABLE computers ADD COLUMN IF NOT EXISTS hold_until TIMESTAMPTZ;
ALTER TABLE computers ADD COLUMN IF NOT EXISTS hold_by    UUID REFERENCES users(id) ON DELETE SET NULL;

COMMENT ON COLUMN computers.hold_until IS 'Е1-и5: ПК придержан под регистрацию до этого момента; прошло — метка не действует';
COMMENT ON COLUMN computers.hold_by    IS 'Е1-и5: кто из персонала придержал — для журнала и разбора «почему занято»';
