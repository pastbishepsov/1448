-- 050: предупреждение о сгорании пакета (спринт Е2-и5а, OPERATOR.md).
--
-- Пакет со сроком (Р11) сгорает молча: гость купил три часа, забыл про них на
-- две недели и обнаружил ноль. Формально всё честно — срок был написан при
-- покупке; по-человечески это способ поссориться с гостем на ровном месте.
-- Монеты в такой ситуации предупреждают (В4-3, coin_burn_warn_days), и пакет
-- должен вести себя так же.
--
-- warned_at на строке выдачи, а не раскопки по журналу уведомлений: у пакета
-- ровно один срок и ровно одно предупреждение — колонка говорит это прямо и
-- заодно отвечает у стойки на «а его предупреждали?».

ALTER TABLE user_packages ADD COLUMN IF NOT EXISTS warned_at TIMESTAMPTZ;

COMMENT ON COLUMN user_packages.warned_at IS 'Е2-и5: когда гостю сказали, что пакет скоро сгорит; NULL — ещё не говорили';

INSERT INTO settings (key, value) VALUES
    ('pack_warn_days', '3')  -- за сколько дней сказать, что пакет сгорает; 0 = не предупреждать
ON CONFLICT (key) DO NOTHING;
