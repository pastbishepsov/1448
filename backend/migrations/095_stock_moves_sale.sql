-- 095 — З19-и4 (OWNER.md, трек З; из «Найдено по дороге» З10-и8, решение основателя 07.11): индекс движений склада по
-- продаже.
--
-- Отмена продажи (возврат в партии — lotsBack, lots_apply.go) и маржа в «Деньгах» (margin.go: продажи периода → их
-- движения) ищут движения склада по sale_id, а индекса по нему не было: каждый раз — полный проход по stock_moves,
-- которые растут с каждой продажей, приходом и корректировкой. Как у заказов кухни (075, kitchen_order_id) — частичный:
-- у прихода и корректировки sale_id пуст, в индекс они не идут.
--
-- Идемпотентна: IF NOT EXISTS.

CREATE INDEX IF NOT EXISTS idx_stock_moves_sale ON stock_moves (sale_id) WHERE sale_id IS NOT NULL;
