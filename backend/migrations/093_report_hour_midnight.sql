-- 093 — З18-и4б (OWNER.md, трек З; решение основателя 07.11, З-Р38): сутки клуба по умолчанию — с полуночи.
--
-- Большинство клубов работают 24/7 — своих «клубных часов» у них нет. Поэтому граница клубных суток (report_hour) по
-- умолчанию теперь 0: сутки 00:00–24:00, как календарь; с Б10-и1 было 8. Свой час границы — опция в «Экономике». Клуб
-- без строки report_hour уже живёт с полуночи (значение по умолчанию в коде); здесь — клубы, у которых сохранена 8:
-- стенд и пилотный клуб (решение основателя — перевести и их). Другой свой час — выбор клуба, его не трогаем.
--
-- Как при правке в «Экономике»: отчёты и сводки смен за прошлые дни пересчитываются по новой границе, а хранимые даты —
-- табель, сдачи кассы — остаются прежними.
--
-- Идемпотентна: после первого прогона строки '8' нет.

UPDATE settings SET value = '0', updated_at = now() WHERE key = 'report_hour' AND value = '8';
