-- 044: сброс пароля гостя админом (спринт Е0-и2, OPERATOR.md).
--
-- Лист основателя: «Смена пароля или любых данных». До этого забытый пароль
-- лечился только SQL — в клубе это означало «приходи, когда владелец за
-- компьютером».
--
-- must_change_password: админ выдал ВРЕМЕННЫЙ пароль и, значит, знает его.
-- Пока гость не заменил его своим, аккаунт считаем чужим наполовину: играть
-- с временным паролем нельзя (409 password_change_required на старте сессии
-- гостём). Посадку админом это НЕ блокирует — у стойки человека опознали
-- лично, и это надёжнее любого пароля.
--
-- tokens_valid_from: «все токены, выданные раньше, недействительны». Отзыв по
-- одному jti (миграция 010) годится для logout и ротации — там токен у нас в
-- руках; при сбросе пароля нужно погасить ВСЕ живые refresh'ы гостя, включая
-- те, которых мы никогда не видели (30 дней жизни — слишком долгий хвост,
-- чтобы смена пароля его не рвала).
--
-- Почему проверка только в /auth/refresh, а не в authMiddleware: middleware
-- принципиально не ходит в базу (JWT самодостаточен), и заводить ему запрос
-- на КАЖДЫЙ запрос ради редкого сброса — плохой размен. handleRefresh и так
-- читает пользователя (проверяет бан), поэтому проверка там бесплатна.
-- Access-токен живёт ≤15 минут и не отзывается — это уже принятый компромисс
-- проекта (STATUS.md), сброс пароля его не меняет.
--
-- Сравнение идёт по секундам (iat в JWT — Unix-секунды), поэтому момент
-- округляется ВВЕРХ до секунды: умирает вся секунда сброса целиком. Первый
-- заход округлял вниз, и refresh, выданный в ту же секунду, отсечку
-- переживал — поймано живым e2e. Свежая пара после смены пароля подписывается
-- ЭТИМ ЖЕ моментом (writeAuthAt), поэтому проходит по построению.

ALTER TABLE users ADD COLUMN IF NOT EXISTS must_change_password BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN IF NOT EXISTS tokens_valid_from    TIMESTAMPTZ;

COMMENT ON COLUMN users.must_change_password IS 'Е0-и2: выдан временный пароль — до смены гость не начинает сессию сам';
COMMENT ON COLUMN users.tokens_valid_from    IS 'Е0-и2: токены с iat раньше этого момента недействительны (проверяется в /auth/refresh)';
