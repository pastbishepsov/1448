-- 088 — З15-и4б (OWNER.md, трек З; решение основателя 23.10): имя смены у записей переименованных шаблонов — из журнала
-- прихода.
--
-- 086 заполнила имя смены в старых записях табеля текущим именем шаблона. Если шаблон переименовали до 086, записи
-- получили новое имя, а человек работал под старым; если такой шаблон потом удалили, в записи осталось то же новое
-- имя. Старое имя есть в журнале: запись, которую человек открыл сам — входом или «Я пришёл» (created_by = он сам), —
-- сервер всегда сопровождал строкой work_start от него же в ту же секунду: «пришёл · День», «вход в систему · День» (до
-- 24.09) или «вход в админку · День». Правило то же, что в 087, только шире: у записи, открытой самим человеком, имя
-- смены — из его строки work_start в пределах двух секунд от создания записи (из нескольких — ближайшая), если оно
-- другое. С 086 сервер пишет имя при открытии записи, и у новых записей оно с журналом совпадает — их правило не меняет.
--
-- Не трогаем: ручные записи владельца — их открыл не сам человек, в журнале у них правка табеля без смены; записи «вне
-- смены» (в журнале «… (вне смены)» — имени нет); записи без строки журнала рядом.
--
-- Идемпотентна: после первого прогона имена совпадают с журналом, повторный ничего не меняет.

WITH found AS (
    SELECT DISTINCT ON (w.id)
           w.id,
           left((regexp_match(a.details, '^(?:пришёл|вход в систему|вход в админку) · (.+)$'))[1], 32) AS name
      FROM work_entries w
      JOIN admin_actions a
        ON a.admin_id = w.user_id
       AND a.action = 'work_start'
       AND a.created_at BETWEEN w.created_at - interval '2 seconds' AND w.created_at + interval '2 seconds'
       AND a.details ~ '^(пришёл|вход в систему|вход в админку) · .+$'
     WHERE w.created_by = w.user_id
     ORDER BY w.id, abs(extract(epoch FROM a.created_at - w.created_at))
)
UPDATE work_entries w
   SET shift_name = found.name
  FROM found
 WHERE w.id = found.id
   AND found.name <> ''
   AND found.name <> w.shift_name;
