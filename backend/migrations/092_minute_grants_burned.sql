-- 092 — З18-и1а (OWNER.md, трек З; №8, З-Р7; решение основателя 05.11): сожжённые минуты — в «Сгорело за период».
--
-- З18-и1: перед удалением зоны мастер в её шторке сжигает живые минуты гостей за монеты и компенсации — остаток выдачи
-- становится 0, гостю — уведомление, в журнал — строка на гостя. Но момента сгорания у выдачи не было, и «Сгорело за
-- период» (З12-и1: обязательства, ушедшие без игры) их не видел — остаток 0 и у отыгранного, и у сожжённого. Теперь
-- сжигание пишет burned_at и burned_minutes (сколько минут сожгли); отчёт берёт их по моменту сгорания, в злотых — по
-- тарифу выдачи rate_pln, как «должны временем» (068).
--
-- Сожжённые до этой миграции (З18-и1, с 02.11) в «Сгорело» не попадут: сколько и у кого сожгли, видно только в журнале
-- (zone_minutes_burn) — восстанавливать выдачи по тексту журнала не стали: у гостя в зоне их может быть несколько.
--
-- Идемпотентна: колонки и индекс — IF NOT EXISTS.

ALTER TABLE minute_grants ADD COLUMN IF NOT EXISTS burned_at      TIMESTAMPTZ;
ALTER TABLE minute_grants ADD COLUMN IF NOT EXISTS burned_minutes INTEGER NOT NULL DEFAULT 0 CHECK (burned_minutes >= 0);

-- «Сгорело за период» ищет сожжённые по моменту сгорания — индекс только по ним
CREATE INDEX IF NOT EXISTS idx_minute_grants_burned ON minute_grants (burned_at) WHERE burned_at IS NOT NULL;

COMMENT ON COLUMN minute_grants.burned_at      IS 'З18-и1а: когда остаток сожгли в мастере удаления зоны (З18-и1); NULL — не сжигали';
COMMENT ON COLUMN minute_grants.burned_minutes IS 'З18-и1а: сколько минут сожгли — остаток на тот момент; 0 — не сжигали';
