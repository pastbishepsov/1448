-- 049: минуты пакета в счёте сессии (спринт Е2-и3, OPERATOR.md).
--
-- У сессии уже есть две колонки «чем оплачено»: coin_minutes_used (минутный
-- запас монет) и money_minutes (кошелёк). Пакет — третий источник, и без
-- своей колонки он растворился бы в одном из них: чек «3 часа из пакета,
-- 40 минут с кошелька» перестал бы сходиться, а обязательство клуба по
-- непроигранным пакетам нечем было бы проверить.
--
-- Порядок расхода (решение основателя, этап III): монеты → минуты пакета →
-- кошелёк. Правило простое: что скорее пропадёт, то и тратим первым. Монеты
-- тают еженедельно (В4-3), пакет может сгореть по сроку (Р11), кошелёк не
-- тает никогда (Г-Р1).

ALTER TABLE sessions ADD COLUMN IF NOT EXISTS pack_minutes_used INTEGER NOT NULL DEFAULT 0;

COMMENT ON COLUMN sessions.pack_minutes_used IS 'Е2-и3: сколько минут этой сессии оплачено пакетом времени';
