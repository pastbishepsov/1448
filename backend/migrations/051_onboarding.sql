-- 051: онбординг админа (спринт Е5-и1, OPERATOR.md).
--
-- Лист основателя: «инструкция при первом входе» (Р9). Новый админ должен
-- увидеть, ГДЕ у стойки что нажимается, а не читать PDF, которого никто не
-- открывает.
--
-- Флаг живёт на СЕРВЕРЕ, а не в localStorage: в клубе десяток машин, админка
-- открывается то с одной, то с другой, и локальный флаг означал бы тур на
-- каждой новой — вместо помощи получилось бы раздражение. Плюс владелец
-- видит, кто из персонала обучение уже прошёл.
--
-- Версия тура — чтобы после крупной правки интерфейса можно было показать его
-- заново, не сбрасывая руками: если tour_version в коде выросла, а у человека
-- записана старая, тур показывается ещё раз.

ALTER TABLE users ADD COLUMN IF NOT EXISTS onboarded_at      TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS onboarded_version INTEGER NOT NULL DEFAULT 0;

COMMENT ON COLUMN users.onboarded_at      IS 'Е5: когда сотрудник прошёл (или пропустил) тур по интерфейсу';
COMMENT ON COLUMN users.onboarded_version IS 'Е5: версия тура, которую он видел; выросла в коде — покажем заново';
