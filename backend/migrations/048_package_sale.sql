-- 048: покупка пакета времени с кошелька (спринт Е2-и2, OPERATOR.md).
--
-- Пакет продают двумя каналами (Р12): у стойки за нал/карту/BLIK и с кошелька
-- — админом или самим гостем из приложения. Второй канал трогает деньги, а
-- кошелёк в проекте меняется ТОЛЬКО через walletApply, который требует вид
-- операции. Без своего вида покупка легла бы под чужим (kitchen_spend или
-- adjust) — и в отчёте «на что ушли деньги гостей» пакеты растворились бы в
-- кухне или в ручных правках владельца.
--
-- Возврат при отмене ошибочной выдачи идёт существующим refund: возврат — он
-- и есть возврат, отдельный вид для него ничего не уточняет.

ALTER TYPE wallet_tx_kind ADD VALUE IF NOT EXISTS 'package_spend';
