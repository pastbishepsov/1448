-- 077 — З10-и3 (OWNER.md, трек З; №68): партии в работе — начальная партия каждой позиции.
--
-- С этой версии каждое движение склада знает свои партии (stockMove → lotsApply): списание — со старых
-- партий первыми, возврат — в те же партии, приход — поставка из одной строки, «нашлось» — партия без
-- цены. Остаток, который уже лежит на складе, становится начальной партией позиции: пришло = осталось =
-- текущий остаток, цена пустая — «начальный остаток». Позиция с нулём партии не получает: первое
-- поступление заведёт свою. Продажи и заказы, сделанные до партий, при отмене вернутся в самую новую
-- партию позиции.
--
-- Идемпотентна: партия заводится только позиции, у которой партий ещё нет.

INSERT INTO stock_lots (club_id, good_id, kind, qty_in, qty_left, received_at, part)
SELECT g.club_id, g.id, 'initial', g.stock, g.stock, now(), 1
  FROM goods g
 WHERE g.stock > 0
   AND NOT EXISTS (SELECT 1 FROM stock_lots l WHERE l.good_id = g.id);
