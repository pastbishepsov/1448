package models

import "time"

// ClubLocation — часовой пояс клуба; main ставит его при старте (З2-и2, OWNER.md №4).
var ClubLocation = time.Local

// ClubDay — тот же календарный день, но полночь по часам клуба (З2-и2).
//
// Колонку date драйвер отдаёт полуночью UTC: «23.09» приходит как 23.09 00:00
// UTC, то есть 02:00 по Варшаве, а полночь клуба — это 22.09 22:00 UTC. Кто
// считал от такой даты время, получал сдвиг: смена «08–20» кончалась в 22:00
// (+2 часа к табелю), правка записи съезжала на 2 часа, «уволен сегодня» выходил
// раньше «нанят сегодня». Переносим дату, а не переводим момент: день остаётся
// тем же, что лежит в базе.
func ClubDay(t time.Time) time.Time {
	if t.IsZero() {
		return t
	}
	return time.Date(t.Year(), t.Month(), t.Day(), 0, 0, 0, 0, ClubLocation)
}

func clubDayPtr(t *time.Time) {
	if t != nil {
		*t = ClubDay(*t)
	}
}
