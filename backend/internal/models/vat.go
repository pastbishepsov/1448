package models

// З13-и1 «Ставки VAT: схема и снимки» (OWNER.md, трек З; №72 «а»; решения основателя 04.10 — бухгалтерия под любого
// бухгалтера, только Польша).
//
// Ставка VAT — у зоны (время за ПК), пакета времени и позиции (товар и кухня). В каждой операции — снимок ставки на
// её момент (миграция 083): пополнение — ставка пополнения из настроек, продажа — ставка позиции, выданный пакет —
// ставка пакета, сессия — ставка зоны ПК. Снимок пишет хук BeforeCreate, если ручка не задала его сама: так ставку
// получает любая операция — у стойки, расчёт кухни, расчёт при выходе, покупка с киоска — и те, что появятся потом.
// NULL в снимке — операция до миграции 083: выгрузка берёт нынешнюю ставку.

import (
	"database/sql"
	"strconv"

	"gorm.io/gorm"
)

// VatZW — «zw»: освобождено от VAT; в колонке ставки — −1.
const VatZW = -1

// VatDefault — ставка новой зоны, пакета и позиции и снимок, когда взять её неоткуда (ПК без зоны, удалённая позиция).
const VatDefault = 23

// VatRates — ставки, которые можно выбрать: польские 23, 8, 5, 0 и «zw». Закон поменяет ставки — меняется эта строка,
// экран берёт список с сервера.
var VatRates = []int{23, 8, 5, 0, VatZW}

// ValidVat — ставка из списка VatRates (чистая, тест).
func ValidVat(v int) bool {
	for _, r := range VatRates {
		if r == v {
			return true
		}
	}
	return false
}

// VatLabel — ставка для людей: «23 %», «zw» (чистая, тест).
func VatLabel(v int) string {
	if v == VatZW {
		return "zw"
	}
	return strconv.Itoa(v) + " %"
}

// vatSnapshot — ставка для снимка: первая колонка первой строки запроса. Запрос — в той же транзакции, но новой
// сессией: текущий запрос хука трогать нельзя. Нет строки или не число — VatDefault.
func vatSnapshot(tx *gorm.DB, q string, args ...any) *int {
	v := VatDefault
	var got sql.NullInt64
	if err := tx.Session(&gorm.Session{NewDB: true}).Raw(q, args...).Row().Scan(&got); err == nil && got.Valid {
		v = int(got.Int64)
	}
	return &v
}
